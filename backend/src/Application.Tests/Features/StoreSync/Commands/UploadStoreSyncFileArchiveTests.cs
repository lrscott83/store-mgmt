namespace Application.Tests.Features.StoreSync.Commands;

/// <summary>
/// El fichero de sincronización tiene que ser un ZIP, no un archivo llamado `.zip`.
///
/// La extensión y el `Content-Type` los elige quien sube: el POS manda `application/zip` para todo.
/// Por eso se mira la CABECERA —la firma del formato—, y solo la cabecera: el contenido sigue siendo
/// opaco (S13), no se abre ni se descifra nada. Lo que se gana es que un archivo que no es un ZIP
/// se rechace con 400 ANTES de ocupar disco y fila, en vez de guardarse y descubrirse al restaurar.
///
/// El ORDEN también importa y está fijado aquí: el tamaño se comprueba antes que la firma, para que
/// un archivo de más de 50 MB siga respondiendo 413 (lo único accionable) y no "no es un ZIP".
/// </summary>
public class UploadStoreSyncFileArchiveTests
{
    private const string SavedKey = "tenant/store/file.zip";
    private const string NotAnArchiveMessage =
        "The uploaded file is not a ZIP archive: the sync upload only accepts the ZIP generated by the POS.";

    /// <summary>Cabecera de fichero local de un ZIP: lo que escribe cualquier compresor.</summary>
    private static readonly byte[] ZipHead = { 0x50, 0x4B, 0x03, 0x04 };

    /// <summary>Fin del directorio central: la cabecera de un ZIP vacío, que también es un ZIP.</summary>
    private static readonly byte[] EmptyZipHead = { 0x50, 0x4B, 0x05, 0x06 };

    private static readonly byte[] NotAnArchive = "no soy un zip"u8.ToArray();

    private readonly Mock<IApplicationUnitOfWork> _unitOfWork = new();
    private readonly Mock<IHttpContextService> _httpContextService = new();
    private readonly Mock<IStoreSyncFileRepository> _fileRepository = new();
    private readonly Mock<IStoreSyncFileStorage> _storage = new();
    private readonly Mock<IStoreRepository> _storeRepository = new();
    private readonly Mock<IUserRepository> _userRepository = new();
    private readonly Mock<IStringLocalizer<I18n>> _localizer = new();
    private readonly Mock<ILogger<UploadStoreSyncFileCommandHandler>> _logger = new();

    private readonly Guid _tenantId = Guid.NewGuid();
    private readonly Guid _ownerId = Guid.NewGuid();
    private readonly Store _store;
    private readonly Guid _storeId;

    private StoreSyncFile? _persisted;

    public UploadStoreSyncFileArchiveTests()
    {
        _localizer
            .Setup(x => x[It.IsAny<string>()])
            .Returns((string name) => new LocalizedString(name, name));

        _localizer
            .Setup(x => x[It.IsAny<string>(), It.IsAny<object[]>()])
            .Returns<string, object[]>((name, args) =>
                new LocalizedString(name, args is { Length: > 0 } ? $"{name}:{string.Join(',', args)}" : name));

        _store = Store.Create("Tienda Centro", _ownerId, true, _tenantId);
        _storeId = _store.Id;

        _httpContextService.Setup(x => x.TenantId).Returns(_tenantId.ToString());
        _httpContextService.Setup(x => x.UserExternalId).Returns(_ownerId.ToString());
        _httpContextService.Setup(x => x.StoreId).Returns(_storeId.ToString());
        _httpContextService.Setup(x => x.IsOwnerAdmin).Returns(true);
        _httpContextService.Setup(x => x.IsReSeller).Returns(false);

        _unitOfWork.Setup(x => x.SaveChangesAsync(It.IsAny<CancellationToken>())).ReturnsAsync(1);

        _storage
            .Setup(x => x.SaveAsync(
                It.IsAny<StoreSyncFileUpload>(),
                It.IsAny<Guid>(),
                It.IsAny<Guid>(),
                It.IsAny<Guid>(),
                It.IsAny<CancellationToken>()))
            .ReturnsAsync(SavedKey);

        _storeRepository
            .Setup(x => x.GetActiveStoresByUserIdAsync(It.IsAny<Guid>(), It.IsAny<Guid?>()))
            .ReturnsAsync(new List<Store> { _store });
        _storeRepository
            .Setup(x => x.GetStoreByIdAsync(It.IsAny<Guid>()))
            .ReturnsAsync(_store);

        _userRepository
            .Setup(x => x.GetUserByIdIncludingStoreAndRoles(It.IsAny<Guid>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(User.Create(_ownerId, "owner", "hash", "Ana María Pérez", "0000000000", null, _tenantId));

        _fileRepository
            .Setup(x => x.AddAsync(It.IsAny<StoreSyncFile>()))
            .Returns((StoreSyncFile file) => Task.FromResult(file))
            .Callback<StoreSyncFile>(file => _persisted = file);
    }

    private UploadStoreSyncFileCommandHandler Handler() => new(
        _unitOfWork.Object,
        _httpContextService.Object,
        _fileRepository.Object,
        _storage.Object,
        _storeRepository.Object,
        _userRepository.Object,
        _localizer.Object,
        _logger.Object);

    private UploadStoreSyncFileCommand Command(byte[] bytes)
        => new(_storeId, new MemoryStream(bytes), "respaldo-tienda.zip", "application/zip", bytes.Length);

    #region ZIP de verdad

    [Theory]
    [InlineData(new byte[] { 0x50, 0x4B, 0x03, 0x04, 0x14, 0x00, 0x00, 0x00 })]
    [InlineData(new byte[] { 0x50, 0x4B, 0x05, 0x06, 0x00, 0x00, 0x00, 0x00 })]
    [InlineData(new byte[] { 0x50, 0x4B, 0x07, 0x08, 0x00, 0x00, 0x00, 0x00 })]
    public async Task Handle_WithARealZip_ShouldStoreItAndPersistTheRow(byte[] bytes)
    {
        var result = await Handler().Handle(Command(bytes), CancellationToken.None);

        result.Succeeded.Should().BeTrue();
        _persisted.Should().NotBeNull();
        _persisted!.SizeBytes.Should().Be(bytes.Length);
        _storage.Verify(x => x.SaveAsync(
            It.IsAny<StoreSyncFileUpload>(), _tenantId, _storeId, It.IsAny<Guid>(), It.IsAny<CancellationToken>()),
            Times.Once);
    }

    /// <summary>
    /// Lo que se guarda es el archivo ENTERO: mirar la cabecera no puede comerse los primeros
    /// bytes, porque el blob tiene que seguir siendo el ZIP que el POS generó.
    /// </summary>
    [Fact]
    public async Task Handle_WhenTheZipIsValid_ShouldStoreTheWholeFileFromTheFirstByte()
    {
        StoreSyncFileUpload? stored = null;
        _storage
            .Setup(x => x.SaveAsync(It.IsAny<StoreSyncFileUpload>(), It.IsAny<Guid>(), It.IsAny<Guid>(),
                It.IsAny<Guid>(), It.IsAny<CancellationToken>()))
            .Callback<StoreSyncFileUpload, Guid, Guid, Guid, CancellationToken>((upload, _, _, _, _) => stored = upload)
            .ReturnsAsync(SavedKey);

        byte[] bytes = ZipHead.Concat(new byte[] { 0x14, 0x00, 0x01, 0x02 }).ToArray();
        await Handler().Handle(Command(bytes), CancellationToken.None);

        stored.Should().NotBeNull();
        stored!.Content.Position.Should().Be(0);
        stored.Content.Read(new byte[bytes.Length], 0, bytes.Length).Should().Be(bytes.Length);
    }

    #endregion

    #region No es un ZIP

    /// <summary>
    /// Extensión `.zip` y `Content-Type` `application/zip` no son una prueba: un archivo cualquiera
    /// con ese nombre se rechaza con 400 y no llega ni al almacenamiento ni a la base.
    /// </summary>
    [Fact]
    public async Task Handle_WhenTheFileIsNotAZip_ShouldRejectItBeforeStoringAnything()
    {
        Func<Task> act = () => Handler().Handle(Command(NotAnArchive), CancellationToken.None);

        var exception = await act.Should().ThrowAsync<ApiException>();
        exception.Which.StatusCode.Should().Be(HttpStatusCode.BadRequest);
        exception.Which.Message.Should().Be(NotAnArchiveMessage);
        _storage.Verify(x => x.SaveAsync(
            It.IsAny<StoreSyncFileUpload>(), It.IsAny<Guid>(), It.IsAny<Guid>(), It.IsAny<Guid>(),
            It.IsAny<CancellationToken>()), Times.Never);
        _fileRepository.Verify(x => x.AddAsync(It.IsAny<StoreSyncFile>()), Times.Never);
        _persisted.Should().BeNull();
    }

    /// <summary>Un archivo más corto que la firma tampoco es un ZIP: "no llega" es "no es".</summary>
    [Fact]
    public async Task Handle_WhenTheFileIsShorterThanTheZipSignature_ShouldRejectIt()
    {
        Func<Task> act = () => Handler().Handle(Command(new byte[] { 0x50, 0x4B }), CancellationToken.None);

        var exception = await act.Should().ThrowAsync<ApiException>();
        exception.Which.StatusCode.Should().Be(HttpStatusCode.BadRequest);
        exception.Which.Message.Should().Be(NotAnArchiveMessage);
        _storage.Verify(x => x.SaveAsync(
            It.IsAny<StoreSyncFileUpload>(), It.IsAny<Guid>(), It.IsAny<Guid>(), It.IsAny<Guid>(),
            It.IsAny<CancellationToken>()), Times.Never);
    }

    /// <summary>
    /// El tamaño manda sobre la firma: un archivo de más de 50 MB responde 413 aunque tampoco sea un
    /// ZIP, porque el tamaño es lo que el usuario puede arreglar. Si la firma fuera primero, el
    /// dueño con un respaldo gigante leería "no es un ZIP" y perdería el tiempo buscando otra causa.
    /// </summary>
    [Fact]
    public async Task Handle_WhenTheFileIsTooLargeAndNotAZip_ShouldRejectItBySize()
    {
        var command = new UploadStoreSyncFileCommand(
            _storeId,
            new MemoryStream(NotAnArchive),
            "enorme.zip",
            "application/zip",
            Domain.Common.Limits.StoreSyncFileLimits.MaxFileSizeInBytes + 1);

        Func<Task> act = () => Handler().Handle(command, CancellationToken.None);

        var exception = await act.Should().ThrowAsync<ApiException>();
        exception.Which.StatusCode.Should().Be(HttpStatusCode.RequestEntityTooLarge);
        _storage.Verify(x => x.SaveAsync(
            It.IsAny<StoreSyncFileUpload>(), It.IsAny<Guid>(), It.IsAny<Guid>(), It.IsAny<Guid>(),
            It.IsAny<CancellationToken>()), Times.Never);
    }

    #endregion
}
